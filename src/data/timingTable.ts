/**
 * 연출 시간 상수 표 (1배속 기준). UI의 타이머와 헤드리스 시간 모델(core/timing.ts, scripts/simulate.ts)이
 * 같은 표를 쓴다. 코드가 아니라 이 표만 고치면 한 판의 길이를 바꿀 수 있다.
 *
 * 한 걸음(한 해)을 화면에 보여 준 뒤 다음 해로 넘어가기까지 기다리는 시간:
 *  - quiet: 아무 일 없이 지나간 해(나이 숫자만 바뀐다)
 *  - narrative: 서술 이벤트가 있던 해(문장을 읽을 시간)
 *  - resolved: 선택지에서 고른 뒤 결과 문구를 읽을 시간
 * 선택지 이벤트(choice)는 타이머가 아니라 사람이 정한다 → READ_SEC 가정치를 쓴다.
 * 사망은 곧바로 엔딩 화면으로 넘어가므로 기다리지 않는다.
 *
 * M4(콘텐츠) 조정: M3 QA 실측(1배속 약 7분)이 SPEC 목표(1배속 약 20~30분)에 못 미쳐 형진 님이 "판당 선택지 약 20~25개 + 1배속 연출을 조금 늘려 목표에 맞춘다"고
 * 정했다(SPEC-001 추가 결정 기록 2026-10-14, R-037). 선택지 수는 EVENT_FREQUENCY(data/lifeTable.ts)와 이벤트 풀이 정하고, 연출 시간은 아래 HOLD_MS가 정한다.
 * 이전 값은 quiet 4000 / narrative 10000 / resolved 8000이었다.
 */
export const HOLD_MS = {
  quiet: 7000,
  narrative: 17000,
  resolved: 13000,
} as const;

/**
 * 가정치: 사람이 선택지 한 개의 상황과 선택지 문구를 읽고 고르는 데 걸리는 시간(초). 시간 모델의 가장 큰 불확실성이다.
 *  - low/median/high: M3 QA 실측(qa/reports/QA-001-M3.md "읽는 시간 추정") — 본문+선택지 평균 75.6자를 묵독 500/600/700자/분으로 읽는 시간 + 고르는 시간 5~15초 → 12~24초, 중앙 약 18초
 *  - upper: 첫 플레이의 망설임을 넉넉히 본 기존 보수 상한(M3까지의 가정치)
 * 목표는 중앙 가정(median)으로 맞추고, 상한 가정(upper)에서도 1배속 수동이 30분을 넘지 않게 한다.
 */
export const READ_SEC = { low: 12, median: 18, high: 24, upper: 30 } as const;

/** 시간 모델의 기본 읽는 시간(초/개): 중앙 가정 */
export const READ_SEC_PER_CHOICE: number = READ_SEC.median;

/** 가정치: "다음 결정으로"를 누르고 새 선택지 화면을 알아보는 데 드는 시간(초). */
export const JUMP_OVERHEAD_SEC = 1;

/** 자동 모드가 선택지 화면을 보여 준 뒤 자동으로 고르기까지의 시간(ms, 1배속 기준). */
export const AUTO_CHOICE_MS = 3000;

/**
 * 목표(SPEC-001 '진행 속도' + 2026-10-14 추가 결정): 1배속 수동 약 20~30분(완료 기준: 30분 이내),
 * 8배속 + 다음 결정으로 "10분 내외"(완료 기준). 아래 값은 시간 모델 테스트가 평균에 대해 단언하는 허용 구간(분)이다.
 *  - manual1xLow~manual1xMax: 1배속 수동의 중앙 가정 평균 / manual1xMax는 상한 가정에서도 모든 판이 넘지 않는 값
 *  - fastLow~fastHigh: 8배속 + 다음 결정으로의 중앙 가정 평균의 허용 구간 **약 7~10.5분**
 *
 * 사실대로 적는다(R-064): 8배속 + 다음 결정으로의 시간은 거의 전부 "읽고 고르는 시간"이라 가정(READ_SEC)이 정한다.
 * 읽기 18초 가정에서 평균 약 7.2~7.6분(실측 `npm run sim`) — SPEC "10분 내외"의 하단(약 -25%)이고, 24초 가정에서 약 9.4~9.9분, 30초 가정에서 약 11.7~12.3분이다.
 * 즉 "약 8~10분"을 달성했다고 쓰지 않는다. 7~10.5분은 가정 18~24초에서 나오는 구간이고, 최종 판정은 사람이 실제로 선택지를 읽고 고르는 시간을 잰 M6 사람 실측이 한다
 * (AI QA의 선택지당 체류는 6.9초였다 → 사람이 그 수준이면 약 3.5~4.5분). 수치를 바꾸는 결정은 실측 뒤로 미룬다.
 */

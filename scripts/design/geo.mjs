/** 위도 중앙값 근처(38°)의 경도 보정 */
const COS = Math.cos((38 * Math.PI) / 180);
const LON0 = 124.0;
const LAT0 = 43.1;

/** [경도, 위도] → 평면(단위: 위도 1°) */
export function project([lon, lat]) {
  return [(lon - LON0) * COS, LAT0 - lat];
}

/** 닫힌 점 목록 → Catmull-Rom 스플라인을 3차 베지어로 바꾼 path 'd' (점 순서 그대로, 닫힘) */
export function smoothClosed(points, tension = 0.5) {
  const n = points.length;
  const f = (v) => Math.round(v * 100) / 100;
  let d = `M${f(points[0][0])} ${f(points[0][1])}`;
  for (let i = 0; i < n; i++) {
    const p0 = points[(i - 1 + n) % n];
    const p1 = points[i];
    const p2 = points[(i + 1) % n];
    const p3 = points[(i + 2) % n];
    const c1 = [p1[0] + ((p2[0] - p0[0]) * tension) / 3, p1[1] + ((p2[1] - p0[1]) * tension) / 3];
    const c2 = [p2[0] - ((p3[0] - p1[0]) * tension) / 3, p2[1] - ((p3[1] - p1[1]) * tension) / 3];
    d += `C${f(c1[0])} ${f(c1[1])} ${f(c2[0])} ${f(c2[1])} ${f(p2[0])} ${f(p2[1])}`;
  }
  return d + 'Z';
}

/** 한 번 가볍게 다듬는다(이웃 평균): 손으로 고른 점의 들쭉날쭉함을 줄이되 곶·만의 특징은 남긴다 */
export function relax(points, w = 0.2) {
  const n = points.length;
  return points.map((p, i) => {
    const a = points[(i - 1 + n) % n];
    const b = points[(i + 1) % n];
    return [p[0] * (1 - 2 * w) + (a[0] + b[0]) * w, p[1] * (1 - 2 * w) + (a[1] + b[1]) * w];
  });
}

/** 윤곽(평면 좌표) */
export function peninsulaPoints() {
  return PENINSULA.map(project);
}

export function bounds(points) {
  const xs = points.map((p) => p[0]);
  const ys = points.map((p) => p[1]);
  return { minX: Math.min(...xs), maxX: Math.max(...xs), minY: Math.min(...ys), maxY: Math.max(...ys) };
}
